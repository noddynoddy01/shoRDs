<#
.SYNOPSIS
  Self-test of the Phase 6C pure logic (Phase6C.Lib.ps1) against the cross-language conformance vectors in .\vectors (generated by the
  Python reference implementation). Windows PowerShell 5.1. Reads the kit files only: no disk writes, no network, no process, no registry.
  Exit code 0 = every vector agrees. Run it BEFORE the dry run. Add -WithJobGuard to also compile and create the kill-on-close job object
  (this writes a temporary file under %TEMP% and creates a Windows job object, no process is started).
.EXAMPLE
  powershell -NoProfile -ExecutionPolicy Bypass -File .\Test-AgentLogic.ps1
#>
[CmdletBinding()]
param([switch]$WithJobGuard)
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'Phase6C.Lib.ps1')
$vec = Join-Path $PSScriptRoot 'vectors'
$script:pass = 0
$script:fail = 0
$script:failed = New-Object System.Collections.ArrayList
function Check {
  param([string]$Name, [bool]$Ok, [string]$Detail = '')
  if ($Ok) { $script:pass = $script:pass + 1 } else { $script:fail = $script:fail + 1; [void]$script:failed.Add($Name + '  ' + $Detail) }
}
function Load-Vec { param([string]$Name) return (Get-Content -LiteralPath (Join-Path $vec $Name) -Raw | ConvertFrom-Json) }

Write-Host ('PowerShell ' + $PSVersionTable.PSVersion.ToString() + ', 64-bit process: ' + [Environment]::Is64BitProcess)
Check 'is-64-bit' ([Environment]::Is64BitProcess) 'run the 64-bit Windows PowerShell'

# strict JSON
$d = Load-Vec 'json-vectors.json'
foreach ($c in $d.cases) {
  $r = ConvertFrom-StrictJson -Text ([string]$c.text) -Rich:([bool]$c.rich)
  Check ('json:' + $c.name) ($r.Ok -eq [bool]$c.ok) ('got ok=' + $r.Ok + ' error=' + $r.Error)
  if ($r.Ok -and $c.ok) { Check ('json-keys:' + $c.name) ((@($r.Value.Keys | Sort-Object) -join ',') -ceq (@($c.keys) -join ',')) '' }
}
# timestamps
$d = Load-Vec 'ts-vectors.json'
foreach ($c in $d.cases) {
  if ($c.PSObject.Properties['s']) {
    $got = ConvertFrom-PilotTimestamp ([string]$c.s)
    $ok = $false
    if ($c.epoch -eq $null) { $ok = ($got -eq $null) } else { $ok = ($got -ne $null -and [long]$got -eq [long]$c.epoch) }
    Check ('ts:' + $c.s) $ok ('got ' + $got)
  } else { Check ('fmt:' + $c.fmt) ((Format-PilotTimestamp ([long]$c.fmt)) -ceq [string]$c.text) '' }
}
# canonical string and HMAC
$d = Load-Vec 'canon-vectors.json'
foreach ($c in $d.cases) {
  $jobObj = (ConvertFrom-StrictJson -Text ([string]$c.text)).Value
  $canon = Get-CanonicalJobString $jobObj
  Check ('canon:' + $jobObj['id']) ($canon -ceq [string]$c.canonical) $canon
  Check ('hmac:' + $jobObj['id']) ((Get-HmacSha256Hex ([string]$d.key) $canon) -ceq [string]$c.hmac) ''
}
# job validation (the security-critical part)
$d = Load-Vec 'job-vectors.json'
foreach ($c in $d.cases) {
  $seen = @{}
  foreach ($s in @($c.seen)) { $seen[[string]$s] = $true }
  $key = [string]$d.key
  if ($c.PSObject.Properties['key']) { $key = [string]$c.key }
  $v = Test-JobText -Text ([string]$c.text) -Stem ([string]$c.stem) -KeyText $key -NowEpoch ([long]$c.now) -Seen $seen
  Check ('job:' + $c.name) ($v.Reason -ceq [string]$c.expect) ('got ' + $v.Reason + ' expected ' + $c.expect)
}
# gates
$d = Load-Vec 'gate-vectors.json'
foreach ($c in $d.cases) {
  $m = @{}
  foreach ($p in $c.m.PSObject.Properties) { $m[$p.Name] = $p.Value }
  $checks = Get-StartGateChecks $m ([int]$c.ngl) ([int]$c.ctx)
  $names = @($checks | ForEach-Object { $_.name }) -join ','
  Check ('gate-names:' + $c.name) ($names -ceq (@($c.names) -join ',')) $names
  $f = @(Get-FailedCheckNames $checks) -join ','
  Check ('gate:' + $c.name) ($f -ceq (@($c.failed) -join ',')) ('got [' + $f + '] expected [' + (@($c.failed) -join ',') + ']')
}
foreach ($t in $d.table) {
  Check ('est:' + $t.ngl + '/' + $t.ctx) ((Get-EstVramMiB ([int]$t.ngl) ([int]$t.ctx)) -eq [int]$t.est) ''
  Check ('need:' + $t.ngl + '/' + $t.ctx) ((Get-RequiredFreeVramMiB ([int]$t.ngl) ([int]$t.ctx)) -eq [int]$t.need) ''
  Check ('ram:' + $t.ctx) ([math]::Abs((Get-MinAvailRamGiB ([int]$t.ctx)) - [double]$t.ram) -lt 0.0001) ''
}
$pol = $d.policy
Check 'policy-vram-limit' ($script:P6C.VramHardLimitMiB -eq [int]$pol.vram_hard_limit_mib) ''
Check 'policy-vram-margin' ($script:P6C.VramMarginMiB -eq [int]$pol.vram_margin_mib) ''
Check 'policy-ram-floor' ([double]$script:P6C.RamFloorGiB -eq [double]$pol.ram_floor_gib) ''
Check 'policy-ram-base' ([double]$script:P6C.RamBaseGiB -eq [double]$pol.ram_base_gib) ''
Check 'policy-ram-step' ([double]$script:P6C.RamPer4096GiB -eq [double]$pol.ram_per_4096_ctx_gib) ''
Check 'policy-disk' ([int]$script:P6C.DiskMinGiB -eq [int]$pol.disk_min_gib) ''
Check 'policy-port' ([int]$script:P6C.Port -eq [int]$pol.port) ''
# emergency brake
$d = Load-Vec 'brake-vectors.json'
foreach ($c in $d.cases) {
  $got = Get-BrakeVerdict $c.s
  Check ('brake:' + $c.name) (([string]$got) -ceq ([string]$c.expect)) ('got [' + $got + '] expected [' + $c.expect + ']')
}
foreach ($c in $d.logs) { Check ('log:' + $c.name) ((Test-LogFatal ([string]$c.text)) -eq [bool]$c.expect) '' }
foreach ($c in $d.addresses) { Check ('addr:' + $c.a) ((Test-ExternalRemote ([string]$c.a)) -eq [bool]$c.external) '' }
# suites
$d = Load-Vec 'suite-vectors.json'
foreach ($c in $d.cases) {
  if ($c.PSObject.Properties['pre']) { $text = [string]$c.pre + ('x' * [int]$c.count) + [string]$c.post } else { $text = [string]$c.text }
  $got = Test-SuiteText $text
  Check ('suite:' + $c.name) ($got -ceq [string]$c.expect) ('got ' + $got + ' expected ' + $c.expect)
}
# server command line
$d = Load-Vec 'args-vectors.json'
foreach ($c in $d.cases) {
  $a = (Get-ServerArgs ([string]$c.model) ([int]$c.ngl) ([int]$c.ctx) ([string]$c.key_file)) -join '|'
  Check ('args:' + $c.ngl + '/' + $c.ctx) ($a -ceq (@($c.args) -join '|')) $a
}
# case-sensitivity guards (PowerShell is case-insensitive by default; the validators must not be)
$seen = @{}
$vv = Test-JobText -Text ('{"schema":"shords-pilot-job/1","id":"JOB-AAAA-0001","type":"server-stop","created_utc":"2026-11-04T13:46:30Z","expires_utc":"2026-11-04T13:56:30Z","params":{},"hmac":"' + ('0' * 64) + '"}') -Stem 'JOB-AAAA-0001' -KeyText 'k' -NowEpoch 1793800000 -Seen $seen
Check 'case:uppercase-id-refused' ($vv.Reason -ceq 'id') $vv.Reason
$vv = Test-JobText -Text ('{"schema":"shords-pilot-job/1","id":"job-aaaa-0001","type":"Server-Stop","created_utc":"2026-11-04T13:46:30Z","expires_utc":"2026-11-04T13:56:30Z","params":{},"hmac":"' + ('0' * 64) + '"}') -Stem 'job-aaaa-0001' -KeyText 'k' -NowEpoch 1793800000 -Seen $seen
Check 'case:mixed-case-type-refused' ($vv.Reason -ceq 'type') $vv.Reason

if ($WithJobGuard) {
  . (Join-Path $PSScriptRoot 'Phase6B.Common.ps1')
  . (Join-Path $PSScriptRoot 'Phase6C.Runtime.ps1')
  $script:St = @{ JobGuard = $null }
  Check 'jobguard-create' (Initialize-JobGuard) 'Add-Type or CreateJobObject failed: closing the window would not stop llama-server'
}

Write-Host ''
Write-Host ('Checks passed: ' + $script:pass + '   failed: ' + $script:fail)
foreach ($f in $script:failed) { Write-Host ('  FAIL  ' + $f) }
if ($script:fail -gt 0) { Write-Host 'PROBLEM: do not run the dry run. Send me this output.'; exit 1 }
Write-Host 'All vectors agree with the reference implementation.'
exit 0
